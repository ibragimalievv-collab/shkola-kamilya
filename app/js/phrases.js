// Полный список для озвучки. names — имена детей, stickers — названия наклеек, titles — названия островов.
export function allPhrases(names, stickers, titles) {
  const out = [...PRAISE, ...HINTS, ...REVEAL, ...titles, ...stickers];
  for (const v of Object.values(P)) if (typeof v === 'string') out.push(v);
  for (const name of names) out.push(P.hi(name), ...PRAISE_NAME(name));
  for (const s of stickers) out.push(P.sticker(s));
  for (const n of [1, 2, 5]) out.push(P.stickersHave(n), P.stickerWait(n), P.homeNext(n), P.streak(n));
  for (const n of PET_NAMES) out.push(n, P.petHello(n));
  out.push(...JOKES, ...HOME_ITEMS.map(i => i[1]));
  return out;
}
