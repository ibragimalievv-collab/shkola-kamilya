// Этап текста = сколько букв из ORDER надо знать, чтобы его прочитать.
export function stageOf(text) {
  let s = 0;
  for (const ch of text.toUpperCase()) {
    const i = ORDER.indexOf(ch);
    if (i >= 0 && i + 1 > s) s = i + 1;
  }
  return s;
}

